// Motion evidence only. No native backend or paid AI calls.
import { createRequire } from 'node:module'
import { mkdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
const require = createRequire(new URL('../../../package.json', import.meta.url))
const { chromium, expect } = require('@playwright/test')
const out = fileURLToPath(new URL('./motion-rebuild/', import.meta.url))
await mkdir(out, { recursive: true })
const browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe' })
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, reducedMotion: 'no-preference', recordVideo: { dir: out, size: { width: 1440, height: 900 } } })
const page = await context.newPage()
const errors = []
page.on('pageerror', error => errors.push(error.message))
await page.goto('http://127.0.0.1:1420/')
await page.waitForLoadState('networkidle')
await page.evaluate(() => document.fonts.ready)
await page.getByRole('button', { name: '开始投篮分析' }).hover()
await page.waitForTimeout(800) // Deliberate viewing cadence in the recording, not an assertion wait.
await page.getByRole('button', { name: '暂停封面轮播' }).click()
await page.waitForTimeout(600)
await page.getByRole('button', { name: '开始投篮分析' }).click()
await expect(page.locator('.upload-page')).toBeVisible()
await page.waitForTimeout(1000)
await page.getByRole('button', { name: '设置', exact: true }).click()
await expect(page.getByRole('dialog')).toBeVisible()
await page.waitForTimeout(600)
await page.getByRole('radio', { name: '深色', exact: true }).check()
await page.waitForTimeout(800)
await page.keyboard.press('Escape')
await expect(page.getByRole('dialog')).not.toBeVisible()
await page.locator('input[type=file]').setInputFiles('tests/fixtures/upload-sample.mp4')
await expect(page.getByLabel('开始时间')).toBeVisible()
await page.getByLabel('开始时间').focus()
await page.keyboard.press('ArrowRight')
await page.waitForTimeout(600)
await page.getByRole('button', { name: '预览裁剪片段' }).click()
await expect(page.getByRole('button', { name: '停止预览裁剪片段' })).toBeVisible()
await page.waitForTimeout(2400)
await page.getByRole('button', { name: '停止预览裁剪片段' }).click()
await page.screenshot({ path: `${out}/end.png` })
const video = page.video()
await context.close()
await video.saveAs(`${out}/workflow.webm`)
await video.delete()
await browser.close()
await writeFile(`${out}/report.json`, JSON.stringify({ errors, viewport: '1440x900', reducedMotion: false, actions: ['首页按钮反馈', '暂停封面', '首页到上传雾化转场', '打开设置', '浅深主题切换', '关闭设置', '导入视频', '键盘调整裁剪起点', '播放和暂停片段'], encoding: 'Playwright bundled WebM encoder; oil-ui MP4 encoder unavailable' }, null, 2))
console.log('Recorded workflow.webm', errors)
